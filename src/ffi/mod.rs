//! Foreign-function interface shells.
//!
//! Mirrors the discipline persist established (`CIRISPersist/src/ffi/`):
//! every CIRIS deployment target reaches the same Rust core. The lens
//! FastAPI integration (Phase 1) is the first PyO3 consumer; agent's
//! Python pipeline (Phase 2) is the second; iOS / Android shells
//! (Phase 3) reach via swift-bridge / uniffi against the same
//! crate.
//!
//! Phase 1: PyO3 (lens cutover).
//! Phase 2: PyO3 (agent adoption).
//! Phase 3: swift-bridge (iOS) + uniffi (Android), composing against
//!          the same Rust surface this module gates.

#[cfg(feature = "_pyffi")]
pub mod pyo3;

// CIRISEdge#960 — the outbound queue through persist's
// `outbound_queue_ops_capsule` (dispatched inside persist's `.so`).
#[cfg(feature = "_pyffi")]
pub mod outbound_ops;

// CIRISEdge#960 — the directory-ops proxy, holding the capsules it points into.
// GENERATED by `tools/gen_kept_directory.py`.
#[cfg(feature = "_pyffi")]
pub(crate) mod kept_directory;

// v0.13.0 (CIRISEdge#36 GO) — UniFFI bindings surface (#25 transport
// mgmt + #26 peer mgmt + #31 identity reads + #28 snapshot reads).
// `uniffi_types` declares the Rust type definitions the UDL references;
// `uniffi_impl` carries the function bodies. Both are re-exported at
// the crate root by `lib.rs` so the `include_scaffolding!` expansion
// resolves names against them. The language-side bindings are
// committed under `bindings/{python,kotlin,swift}/`.
#[cfg(feature = "ffi-uniffi")]
pub mod uniffi_types;

#[cfg(feature = "ffi-uniffi")]
pub mod uniffi_impl;

// v0.14.0 (CIRISEdge#32) — Links FFI surface (link_list / link_count /
// link_open / link_teardown / link_request). Split into its own
// module so the lifecycle hooks stay close to the Reticulum-specific
// transport code without growing `uniffi_impl.rs` beyond the v0.13.0
// reads / mgmt scope.
#[cfg(feature = "ffi-uniffi")]
pub mod uniffi_impl_links;

// v0.15.0 (CIRISEdge#33) — Routing-table FFI surface (paths /
// blackhole / rate / tunnels / announce / reverse). Same per-feature
// split rationale as `uniffi_impl_links`: keeps the
// Reticulum-specific surface close to the transport code without
// growing the top-level UniFFI impl module past the v0.13.0 reads /
// mgmt scope.
#[cfg(feature = "ffi-uniffi")]
pub mod uniffi_impl_routing;

// v44 (CC 5.4.3 / 5.4.6) — the mobile shaping + Anonymous Tier surface:
// device state in, shaping and tier status out.
#[cfg(feature = "ffi-uniffi")]
pub mod uniffi_impl_shaping;
